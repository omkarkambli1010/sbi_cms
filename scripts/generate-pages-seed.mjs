#!/usr/bin/env node
/**
 * Generates db/seeds/004_about.sql, 005_leadership.sql and 006_sector.sql from
 * the marketing site's own constants.
 *
 *   node scripts/generate-pages-seed.mjs
 *
 * Same reasoning as generate-seed.mjs: with these seeds loaded the three pages
 * must render exactly what they render from the built-in constants, so the
 * copy is read from the constants rather than typed a second time. Copy that
 * lives in a component instead (form labels, column headers, breadcrumb
 * defaults) is listed below, each block marked with the file it was read from.
 *
 *   SBI_SITE_DIR   a checkout that has src/constants/sbi-{about,leadership,sector}.ts
 *                  (default D:/tmp/corporate-web-rev)
 */

import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import ts from "typescript";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SITE = process.env.SBI_SITE_DIR ?? "D:/tmp/corporate-web-rev";

async function load(name) {
  const file = path.join(SITE, "src", "constants", `${name}.ts`);
  let source;
  try {
    source = readFileSync(file, "utf8");
  } catch {
    console.error(`Could not read ${file}. Point SBI_SITE_DIR at a checkout that has it.`);
    process.exit(1);
  }
  const js = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  const dir = mkdtempSync(path.join(tmpdir(), "sbi-pages-"));
  const out = path.join(dir, `${name}.mjs`);
  writeFileSync(out, js, "utf8");
  return import(pathToFileURL(out).href);
}

