/* --- SQL literals ---------------------------------------------------------- */

const lit = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);

/** A JSON value as a dollar-quoted jsonb literal. The tag cannot occur in content. */
const json = (obj) => `$j$${JSON.stringify(obj)}$j$::jsonb`;

const HEADER = (file, what) => `-- ============================================================================
-- ${file} — ${what}
--
-- GENERATED by scripts/generate-pages-seed.mjs from the marketing site's
-- constants. Do not edit by hand; change the constants (or the generator) and
-- regenerate. Re-runnable: pages and sections are upserted, lists are replaced
-- wholesale, so running it after an editor has changed copy puts the shipped
-- copy back.
-- ============================================================================

SET search_path = cms, public;

BEGIN;

-- Media ids are not known until the assets are registered, so content below
-- names an image as "@media:<url>" and this resolves it. Dropped on commit.
CREATE OR REPLACE FUNCTION pg_temp.seed_media(p JSONB) RETURNS JSONB
LANGUAGE sql AS $$
  SELECT jsonb_strip_nulls(coalesce(jsonb_object_agg(
           e.key,
           CASE WHEN right(e.key, 6) = '_media' AND jsonb_typeof(e.value) = 'string'
                THEN to_jsonb((SELECT m.id FROM cms.media_assets m WHERE m.url = substr(e.value #>> '{}', 8)))
                ELSE e.value END), '{}'::jsonb))
    FROM jsonb_each(p) AS e;
$$;
`;

const MIME = { png: "image/png", svg: "image/svg+xml", jpg: "image/jpeg", webp: "image/webp" };

/** media_create upserts by url, so an editor's upload of the same path survives. */
function mediaSql(urls) {
  return [...new Set(urls)]
    .map((url) => {
      const file = url.split("/").pop();
      const ext = file.split(".").pop();
      return `SELECT cms.media_create(${lit(url)}, ${lit(file)}, ${lit(MIME[ext] ?? "application/octet-stream")}, '', ${lit(file)}, NULL, NULL, NULL, ${lit(url.split("/")[2])});`;
    })
    .join("\n");
}

const m = (url) => `@media:${url}`;

function pageSql({ slug, name, route, sections }) {
  return `
INSERT INTO cms.pages (slug, name, route)
VALUES (${lit(slug)}, ${lit(name)}, ${lit(route)})
ON CONFLICT (slug) DO UPDATE SET name = EXCLUDED.name, route = EXCLUDED.route;

INSERT INTO cms.page_sections (page_id, section_key, name, display_order)
SELECT p.id, v.section_key, v.name, v.display_order
  FROM cms.pages p,
       (VALUES
${sections.map(([k, n], i) => `         (${lit(k)}, ${lit(n)}, ${i + 1})`).join(",\n")}
       ) AS v(section_key, name, display_order)
 WHERE p.slug = ${lit(slug)}
ON CONFLICT (page_id, section_key) DO UPDATE
   SET name = EXCLUDED.name, display_order = EXCLUDED.display_order;
`;
}

const block = (page, section, data) =>
  `SELECT cms.content_block_update(${lit(page)}, ${lit(section)}, pg_temp.seed_media(${json(data)}));`;

function items(page, section, collection, rows) {
  const id = `cms.section_id_for(${lit(page)}, ${lit(section)})`;
  return [
    `DELETE FROM cms.content_items WHERE section_id = ${id} AND collection = ${lit(collection)};`,
    ...rows.map(
      ({ key = null, active = true, ...data }, i) =>
        `SELECT cms.content_item_create(${id}, ${lit(collection)}, ${lit(key)}, pg_temp.seed_media(${json(data)}), ${i + 1});` +
        (active ? "" : ""),
    ),
  ].join("\n");
}

const seo = (slug, title, description, keywords, canonical) =>
  `SELECT cms.seo_upsert(${lit(slug)}, ${lit(title)}, ${lit(description)}, ARRAY[${keywords.map(lit).join(", ")}], ${lit(canonical)}, NULL, NULL, NULL, 'index,follow');`;

const crumbs = (list) => list.map(([label, href]) => ({ label, ...(href ? { href } : {}) }));

